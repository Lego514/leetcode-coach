/** 這題值得檢查的邊界情況；自己新增的題目沒有 */
export function edgeCasesFor(problemId: number, locale: Locale = 'zh-TW'): string | undefined {
  return (locale === 'en' ? EDGE_CASES_EN : EDGE_CASES)[problemId];
}

/** 邊界情況拆成一條一條，提示裡用清單顯示 */
export function edgeCaseList(problemId: number, locale: Locale = 'zh-TW'): string[] {
  const text = edgeCasesFor(problemId, locale);
  if (!text) return [];
  return text
    .split(/[;；]\s*/)
    .map((item) => item.trim().replace(/[.。]$/, ''))
    .filter(Boolean);
}
